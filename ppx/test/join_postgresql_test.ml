open! Base

(* Local Stdlib opens also support the unqualified calls generated by upstream. *)

let exec conn query =
  PGOCaml.prepare conn ~query ();
  ignore (PGOCaml.execute conn ~params:[] () : string option list list)
;;

let setup conn =
  exec conn "DROP TABLE IF EXISTS join_links";
  exec conn "DROP TABLE IF EXISTS join_people";
  exec
    conn
    "CREATE TABLE join_people (id integer NOT NULL, name text NOT NULL, note text)";
  exec
    conn
    "CREATE TABLE join_links (id integer NOT NULL, person_id integer NOT NULL, label text, active boolean NOT NULL)";
  exec
    conn
    "INSERT INTO join_people VALUES (1, 'Ada', NULL), (2, 'Grace', 'note'), (3, 'Lin', NULL)";
  exec
    conn
    "INSERT INTO join_links VALUES (10, 1, 'first', true), (11, 1, NULL, false), (12, 2, 'second', true), (13, 99, 'orphan', true)"
;;

let scalar conn (person : int32) : int32 list =
  let open! Stdlib in
  [%pgsql
    conn
      "SELECT l.id FROM join_people p JOIN join_links l ON p.id = l.person_id AND p.id = $person ORDER BY l.id"]
;;

let page conn (minimum : int32) (name : string) (limit : int64) (offset : int64)
  : (int32 * string option) list
  =
  let open! Stdlib in
  [%pgsql
    conn
      "SELECT l.id, l.label FROM join_people p INNER JOIN join_links l ON p.id = l.person_id AND l.id >= $minimum WHERE p.name = $name ORDER BY l.id LIMIT $limit OFFSET $offset"]
;;

let self_join conn : (int32 * int32 * string) list =
  let open! Stdlib in
  [%pgsql
    conn
      "SELECT p.id, l.id, other.name FROM join_people p JOIN join_links l ON p.id = l.person_id JOIN join_people other ON other.id = p.id WHERE l.active ORDER BY l.id"]
;;

let wildcard conn
  : (int32 * string * string option * int32 * int32 * string option * bool) list
  =
  let open! Stdlib in
  [%pgsql
    conn
      "SELECT * FROM join_people p JOIN join_links l ON p.id = l.person_id WHERE l.id = 11"]
;;

type t =
  { identifier : int32
  ; name : string
  ; label : string option
  }

let t_of_pgocaml row = { identifier = row#identifier; name = row#name; label = row#label }

let objects conn : t list =
  let rows =
    let open! Stdlib in
    [%pgsql.object
      conn
        "SELECT p.id AS identifier, p.name, l.label FROM join_people p JOIN join_links l ON p.id = l.person_id ORDER BY l.id"]
  in
  List.map rows ~f:t_of_pgocaml
;;

let optional conn : (int32 option * string option) list =
  let open! Stdlib in
  [%pgsql
    conn
      "nullable-results"
      "SELECT p.id, l.label FROM join_people p JOIN join_links l ON p.id = l.person_id WHERE l.id = 11"]
;;

let qualified_wildcard conn : (int32 * string * string option) list =
  let open! Stdlib in
  [%pgsql
    conn
      "SELECT p.* FROM public.join_people p JOIN public.join_links l ON p.id = l.person_id WHERE l.id = 10"]
;;

let () =
  let conn = PGOCaml.connect ?host:(Stdlib.Sys.getenv_opt "PGHOST") () in
  Exn.protect
    ~finally:(fun () -> PGOCaml.close conn)
    ~f:(fun () ->
      setup conn;
      assert (List.equal Int32.equal (scalar conn 1l) [ 10l; 11l ]);
      assert (List.equal Int32.equal (scalar conn 2l) [ 12l ]);
      assert (List.is_empty (scalar conn 3l));
      let rows = page conn 10l "Ada" 1L 1L in
      assert (
        List.equal
          (fun (a, b) (x, y) -> Int32.equal a x && Option.equal String.equal b y)
          rows
          [ 11l, None ]);
      let rows = self_join conn in
      assert (
        List.equal
          (fun (a, b, c) (x, y, z) ->
             Int32.equal a x && Int32.equal b y && String.equal c z)
          rows
          [ 1l, 10l, "Ada"; 2l, 12l, "Grace" ]);
      let person, name, note, link, owner, label, active = List.hd_exn (wildcard conn) in
      assert (Int32.equal person 1l && String.equal name "Ada" && Option.is_none note);
      assert (
        Int32.equal link 11l && Int32.equal owner 1l && Option.is_none label && not active);
      let rows = objects conn in
      assert (
        List.equal
          (fun a b ->
             Int32.equal a.identifier b.identifier
             && String.equal a.name b.name
             && Option.equal String.equal a.label b.label)
          rows
          [ { identifier = 1l; name = "Ada"; label = Some "first" }
          ; { identifier = 1l; name = "Ada"; label = None }
          ; { identifier = 2l; name = "Grace"; label = Some "second" }
          ]);
      List.iter rows ~f:(fun row ->
        Stdlib.Printf.printf
          "%ld:%s:%s\n"
          row.identifier
          row.name
          (Option.value row.label ~default:"NULL"));
      assert (
        List.equal
          (fun (a, b) (x, y) ->
             Option.equal Int32.equal a x && Option.equal String.equal b y)
          (optional conn)
          [ Some 1l, None ]);
      let id, name, note = List.hd_exn (qualified_wildcard conn) in
      assert (Int32.equal id 1l && String.equal name "Ada" && Option.is_none note))
;;
